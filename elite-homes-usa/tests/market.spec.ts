import { expect, test } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { join } from 'node:path';

const fixture = join(process.cwd(), 'public', 'images', 'family.webp');
const film = join(process.cwd(), 'public', 'videos', 'home-film.mp4');

test('seller photos stay private until approved, buyers submit cash offers, and the owner closes intake', async ({ page, browser, baseURL }) => {
  const street = '27 Review Lane ' + randomUUID().slice(0,8);
  await page.goto('/sell');
  await page.getByLabel('Street address').fill(street);
  await page.getByLabel('ZIP code').fill('32218');
  await page.getByLabel('City', { exact: true }).fill('Jacksonville');
  await page.getByLabel('Property type').selectOption('Single-family homes');
  await page.getByLabel('Bedrooms').fill('3');
  await page.getByLabel('Bathrooms').fill('2');
  await page.getByLabel('Asking price (USD)').fill('250000');
  await page.getByLabel('Condition, updates and anything we should know').fill('Private condition notes for the owner.');
  await page.getByLabel('Choose photos').setInputFiles(fixture);
  await expect(page.getByAltText('Property photo 1')).toBeVisible();
  await page.getByLabel('Full name').fill('Sample Seller');
  await page.getByLabel('Email', { exact: true }).fill('seller@example.com');
  await page.getByLabel('Phone').fill('9045550100');
  await page.getByRole('checkbox', { name: /I have permission to share/ }).check();
  await page.getByRole('button', { name: 'Send Property for Review' }).click();
  await expect(page.getByRole('heading', { name: 'Sample submission saved.' })).toBeVisible();

  const visitor = await browser.newContext({ baseURL });
  expect((await visitor.request.get('/api/admin/market')).status()).toBe(401);
  await page.goto('/admin');
  await page.getByLabel('Owner access secret').fill(process.env.ELITE_TEST_SECRET!);
  await page.getByRole('button', { name: 'Sign In', exact: true }).click();
  const summary = page.locator('summary').filter({ hasText: street });
  await summary.click();
  const seller = page.locator('.market-record[open]');
  await expect(seller.getByRole('link', { name: 'seller@example.com' })).toHaveAttribute('href', 'mailto:seller@example.com');
  const photo = await seller.getByAltText('Submitted photo 1').getAttribute('src');
  expect(photo).toMatch(/^\/api\/media\//);
  expect((await page.request.get(photo!)).status()).toBe(200);
  expect((await visitor.request.get(photo!)).status()).toBe(404);
  await seller.getByLabel('Property status').selectOption('Published');
  await seller.getByLabel('Public listing title').fill('Jacksonville Courtyard Home ' + street.slice(-8));
  await seller.getByLabel('Public description').fill('Three-bedroom home with a quiet courtyard.');
  await seller.getByRole('checkbox', { name: 'Photo 1' }).check();
  await seller.getByRole('button', { name: 'Save Property' }).click();
  await expect(page.locator('.owner-toast')).toContainText('confirm publishing permission');
  await seller.getByLabel('I have the seller’s permission', { exact: false }).check();
  await seller.getByRole('button', { name: 'Save Property' }).click();
  await expect(seller.getByRole('link', { name: 'View listing' })).toBeVisible();

  const listing = (await seller.getByRole('link', { name: 'View listing' }).getAttribute('href'))!;
  expect((await visitor.request.get(photo!)).status()).toBe(200);
  const buyer = await visitor.newPage();
  await buyer.goto('/buy');
  await expect(buyer.locator(`a[href="${listing}"]`)).toBeVisible();
  await buyer.locator(`a[href="${listing}"]`).click();
  await expect(buyer.getByText('Three-bedroom home with a quiet courtyard.')).toBeVisible();
  await expect(buyer.getByText(/Private condition notes/)).toHaveCount(0);
  await buyer.getByRole('button', { name: /Enlarge/ }).click();
  await expect(buyer.getByRole('dialog', { name: 'Property photos' })).toBeVisible();
  await buyer.keyboard.press('Escape');
  await buyer.getByLabel('Your cash offer (USD)').fill('242000');
  await buyer.getByLabel('Full name').fill('Example Buyer');
  await buyer.getByLabel('Email', { exact: true }).fill('buyer@example.com');
  await buyer.getByLabel('Phone').fill('9045550123');
  await buyer.getByLabel('Preferred closing timeline').fill('Within 30 days');
  await buyer.getByRole('button', { name: 'Send Cash Offer' }).click();
  await expect(buyer.getByRole('heading', { name: 'Sample submission saved.' })).toBeVisible();

  await page.reload();
  await page.getByRole('button', { name: 'Buyer offers' }).click();
  await page.locator('summary').filter({ hasText: '$242,000' }).click();
  const offer = page.locator('.market-record[open]');
  await expect(offer.getByRole('link', { name: 'buyer@example.com' })).toHaveAttribute('href', 'mailto:buyer@example.com');
  await offer.getByLabel('Offer status').selectOption('Contacted');
  await offer.getByLabel('Private note').fill('Discussed timing with buyer.');
  await offer.getByRole('button', { name: 'Save Offer' }).click();
  await expect(offer.getByText('Discussed timing with buyer.')).toBeVisible();
  await page.getByRole('button', { name: 'Seller submissions' }).click();
  await summary.click();
  await seller.getByLabel('Property status').selectOption('Sold');
  await seller.getByRole('button', { name: 'Save Property' }).click();
  await expect(summary).toContainText('Sold');
  expect((await visitor.request.get(photo!)).status()).toBe(404);
  expect((await visitor.request.get(listing)).status()).toBe(404);
  const closed = await visitor.request.post('/api/market/offer', { headers: { Origin: baseURL! }, data: { requestId: randomUUID(), listing: listing.split('/').pop(), amount: 220000, name: 'Late Buyer', email: 'late@example.com', phone: '9045550124' } });
  expect(closed.status()).toBe(409);
  await visitor.close();
});

test('owner publishes and removes website media, replaces the hero film and moderates visitor reviews', async ({ page, browser, baseURL }) => {
  const title = 'Careful communication ' + randomUUID().slice(0,7);
  await page.goto('/reviews');
  await page.getByLabel('Display name', { exact: true }).fill('Sample Reviewer');
  await page.getByLabel('Email (private)').fill('review@example.com');
  await page.getByLabel('Review title').fill(title);
  await page.getByLabel('Your review', { exact: true }).fill('The team explained the process well.');
  await page.getByRole('checkbox', { name: /may publish/ }).check();
  await page.getByRole('button', { name: 'Submit for Review' }).click();
  await expect(page.getByRole('heading', { name: 'Sample submission saved.' })).toBeVisible();
  await page.reload();
  await expect(page.getByText(title)).toHaveCount(0);
  await page.goto('/admin');
  await page.getByLabel('Owner access secret').fill(process.env.ELITE_TEST_SECRET!);
  await page.getByRole('button', { name: 'Sign In', exact: true }).click();
  await page.getByRole('button', { name: 'Reviews', exact: true }).click();
  const record = page.locator('summary').filter({ hasText: title });
  await record.click();
  await page.locator('.market-record[open]').getByLabel('Visibility').selectOption('Published');
  await page.getByRole('button', { name: 'Save Review' }).click();
  await expect(record).toContainText('Published');

  const reader = await browser.newContext({ baseURL });
  const home = await reader.newPage();
  await home.goto('/reviews');
  await expect(home.getByRole('heading', { name: title })).toBeVisible();
  await expect(home.getByText('review@example.com')).toHaveCount(0);

  await page.getByRole('button', { name: 'Website and media' }).click();
  await page.getByLabel('Upload a media file').setInputFiles(fixture);
  await expect(page.getByRole('status')).toContainText('Photo uploaded.');
  const hero = page.locator('.image-editor').filter({ has: page.getByRole('heading', { name: 'Hero photos' }) });
  const gallery = page.locator('.image-editor').filter({ has: page.getByRole('heading', { name: 'Homepage gallery' }) });
  for (const [editor, text] of [[hero, 'Approved hero photograph'], [gallery, 'Approved gallery photograph']] as const) {
    await editor.locator('select').selectOption({ index: 1 });
    await editor.getByRole('button', { name: 'Add image' }).click();
    await editor.getByLabel('Photo 1 description').fill(text);
  }
  await page.getByLabel('Hero headline').fill('Move ahead.');
  await page.getByLabel('Upload a media file').setInputFiles(film);
  await expect(page.getByRole('status')).toContainText('Video uploaded.');
  await page.getByRole('button', { name: 'Save Website Changes' }).click();
  await expect(page.getByRole('status')).toContainText('Changes saved.');

  await home.goto('/');
  await expect(home.getByRole('heading', { level: 1 })).toContainText('Move ahead.');
  await expect(home.getByAltText('Approved hero photograph')).toBeVisible();
  await expect(home.getByRole('button', { name: 'Enlarge Approved gallery photograph' })).toBeVisible();
  const photo = (await home.getByAltText('Approved hero photograph').getAttribute('src'))!;
  expect((await reader.request.get(photo)).status()).toBe(200);
  await home.getByRole('button', { name: 'View film' }).click();
  const video = home.getByRole('dialog', { name: 'Elite Homes USA film' }).locator('video');
  const src = (await video.getAttribute('src'))!;
  expect((await reader.request.get(src, { headers: { Range: 'bytes=0-19' } })).status()).toBe(206);
  await expect.poll(() => video.evaluate(el => (el as HTMLVideoElement).readyState)).toBeGreaterThan(0);
  await home.keyboard.press('Escape');

  await hero.getByRole('button', { name: 'Remove photo 1' }).click();
  await gallery.getByRole('button', { name: 'Remove photo 1' }).click();
  await page.getByLabel('Hero headline').fill('');
  await page.getByLabel('Video source').selectOption('url');
  await page.getByLabel('HTTPS video URL').fill('https://youtu.be/M7lc1UVf-VE');
  await page.getByRole('button', { name: 'Save Website Changes' }).click();
  await expect(page.getByRole('status')).toContainText('Changes saved.');
  expect((await reader.request.get(photo)).status()).toBe(404);
  expect((await reader.request.get(src)).status()).toBe(404);
  await home.reload();
  await home.getByRole('button', { name: 'View film' }).click();
  await expect(home.locator('iframe')).toHaveAttribute('src', /youtube-nocookie\.com\/embed\/M7lc1UVf-VE/);
  await page.getByLabel('Video source').selectOption('default');
  await page.getByRole('button', { name: 'Save Website Changes' }).click();
  await expect(page.getByRole('status')).toContainText('Changes saved.');
  await reader.close();
});
